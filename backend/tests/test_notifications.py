from datetime import timedelta
from zoneinfo import ZoneInfo
from datetime import datetime

from app.scheduled_jobs import run_daily_jobs


def test_notifications_are_created_by_job_and_scoped_per_user(client, database, operator_token, admin_token):
    today = datetime.now(ZoneInfo("Asia/Tashkent")).date()
    operator_headers = {"Authorization": f"Bearer {operator_token}"}
    person = client.post("/api/residents", headers=operator_headers, json={
        "first_name": "Zuhra", "last_name": "Rahimova", "payment_period_days": 30,
        "agreed_price": "300000", "billing_start": (today - timedelta(days=31)).isoformat(),
    }).json()

    # GET remains read-only; due notices are generated by the scheduled job.
    assert not any(item["kind"] == "OVERDUE" for item in client.get("/api/notifications", headers=operator_headers).json())
    result = run_daily_jobs(database, today)
    assert result["reminders_created"] == 2
    run_daily_jobs(database, today)

    operator_reminders = client.get("/api/notifications", headers=operator_headers)
    admin_headers = {"Authorization": f"Bearer {admin_token}"}
    admin_reminders = client.get("/api/notifications", headers=admin_headers)
    assert any(item["entity_id"] == person["id"] and item["kind"] == "OVERDUE" for item in operator_reminders.json())
    assert any(item["entity_id"] == person["id"] and item["kind"] == "OVERDUE" for item in admin_reminders.json())

    assert client.post("/api/notifications/read-all", headers=operator_headers).status_code == 204
    assert client.get("/api/notifications", headers=operator_headers).json() == []
    assert len(client.get("/api/notifications", headers=admin_headers).json()) == 1
